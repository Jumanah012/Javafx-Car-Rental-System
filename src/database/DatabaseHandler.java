    public void populateDefaultVehicles(){
        String checkSql = "SELECT COUNT(*) AS total FROM Vehicles";
        try (Statement stmt = connection.createStatement()) {
            ResultSet rs = stmt.executeQuery(checkSql);
            if(rs.next()){
                int count = rs.getInt("total");
                if(count == 0){

                    String insertSql = "INSERT INTO Vehicles (make, model, year, availability_status, rental_price) VALUES (?, ?, ?, ?, ?)";
                    try (PreparedStatement pstmt = connection.prepareStatement(insertSql)) {

                        List<Vehicle> defaultVehicles = getDefaultVehicles();
                        for(Vehicle v : defaultVehicles){
                            pstmt.setString(1, v.getMake());
                            pstmt.setString(2, v.getModel());
                            pstmt.setInt(3, v.getYear());
                            pstmt.setString(4, v.getAvailabilityStatus());
                            pstmt.setDouble(5, v.getRentalPrice());
                            pstmt.addBatch();
                        }
                        pstmt.executeBatch();
                        System.out.println("Default vehicles added to the database.");
                    }
                } else {
                    System.out.println("Vehicles already exist in the database.");
                }
            }
        } catch (SQLException e) {
            System.err.println("Error checking or populating default vehicles.");
            e.printStackTrace();
        }
    }

