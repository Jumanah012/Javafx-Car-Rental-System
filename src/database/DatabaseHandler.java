    public void createTables() {
        String createUsersTable = "CREATE TABLE Users ("
                + "user_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "name VARCHAR2(100) NOT NULL, "
                + "email VARCHAR2(100) UNIQUE NOT NULL, "
                + "password VARCHAR2(100) NOT NULL, "
                + "role VARCHAR2(50) NOT NULL"
                + ")";

        String createVehiclesTable = "CREATE TABLE Vehicles ("
                + "vehicle_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "make VARCHAR2(50) NOT NULL, "
                + "model VARCHAR2(50) NOT NULL, "
                + "year NUMBER(4) NOT NULL, "
                + "availability_status VARCHAR2(20) NOT NULL, "
                + "rental_price NUMBER(10,2) NOT NULL"
                + ")";

        String createBookingsTable = "CREATE TABLE Bookings ("
                + "booking_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "customer_id NUMBER NOT NULL, "
                + "vehicle_id NUMBER NOT NULL, "
                + "rental_date DATE NOT NULL, "
                + "return_date DATE NOT NULL, "
                + "status VARCHAR2(20) NOT NULL, "
                + "FOREIGN KEY (customer_id) REFERENCES Users(user_id), "
                + "FOREIGN KEY (vehicle_id) REFERENCES Vehicles(vehicle_id)"
                + ")";

        try (Statement stmt = connection.createStatement()) {

            try {
                stmt.execute(createUsersTable);
                System.out.println("Users table created successfully.");
            } catch (SQLException e) {
                if (e.getErrorCode() == 955) { 
                    System.out.println("Users table already exists.");
                } else {
                    throw e;
                }
            }

            try {
                stmt.execute(createVehiclesTable);
                System.out.println("Vehicles table created successfully.");
            } catch (SQLException e) {
                if (e.getErrorCode() == 955) {
                    System.out.println("Vehicles table already exists.");
                } else {
                    throw e;
                }
            }

            try {
                stmt.execute(createBookingsTable);
                System.out.println("Bookings table created successfully.");
            } catch (SQLException e) {
                if (e.getErrorCode() == 955) {
                    System.out.println("Bookings table already exists.");
                } else {
                    throw e;
                }
            }

        } catch (SQLException e) {
            System.err.println("Error creating tables.");
            e.printStackTrace();
        }

        ensureDefaultUsers();

        populateDefaultVehicles();
    }

